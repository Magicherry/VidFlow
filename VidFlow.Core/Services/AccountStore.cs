using System.Text;
using VidFlow.Models;

namespace VidFlow.Services;

public sealed record CookieRecord(string Domain, string Path, string Name, string Value, bool Secure, bool HttpOnly, long Expires);

/// <summary>The cookies.txt produced by in-app login (see the app's LoginWindow), in Netscape format for yt-dlp.</summary>
public static class AccountStore
{
    public static string CookieFile => Path.Combine(AppSettings.DataDir, "cookies.txt");

    public static string Domain(Platform p) => p switch
    {
        Platform.Bilibili => "bilibili.com",
        Platform.Douyin => "douyin.com",
        _ => "youtube.com",
    };

    /// <summary>Cookies that only exist while signed in.</summary>
    public static IReadOnlyList<string> SessionCookieNames(Platform p) => p switch
    {
        Platform.Bilibili => ["SESSDATA"],
        Platform.Douyin => ["sessionid", "sessionid_ss"],
        _ => ["SAPISID", "__Secure-3PAPISID", "LOGIN_INFO"],
    };

    public static bool HasAnyLogin => IsLoggedIn(Platform.Bilibili) || IsLoggedIn(Platform.YouTube) || IsLoggedIn(Platform.Douyin);

    /// <summary>The cookie file to pass to yt-dlp, or null when nobody is signed in.</summary>
    public static string? LoginCookieFileOrNull => HasAnyLogin ? CookieFile : null;

    public static bool IsLoggedIn(Platform p)
    {
        try
        {
            if (!File.Exists(CookieFile)) return false;
            var names = SessionCookieNames(p);
            var domain = Domain(p);
            return File.ReadLines(CookieFile)
                .Select(l => l.Split('\t'))
                .Any(f => f.Length >= 7 && f[0].EndsWith(domain, StringComparison.OrdinalIgnoreCase) && names.Contains(f[5]));
        }
        catch (IOException)
        {
            return false;
        }
    }

    public static string ToNetscape(IEnumerable<CookieRecord> cookies)
    {
        var sb = new StringBuilder("# Netscape HTTP Cookie File\n# Generated by VidFlow\n\n");
        foreach (var c in cookies.DistinctBy(c => (c.Domain, c.Path, c.Name)))
        {
            var prefix = c.HttpOnly ? "#HttpOnly_" : "";
            var includeSub = c.Domain.StartsWith('.') ? "TRUE" : "FALSE";
            sb.Append($"{prefix}{c.Domain}\t{includeSub}\t{c.Path}\t{(c.Secure ? "TRUE" : "FALSE")}\t{c.Expires}\t{c.Name}\t{c.Value}\n");
        }
        return sb.ToString();
    }

    /// <summary>Raised after the cookie file is rewritten (sign-in or sign-out), from whichever thread wrote it.</summary>
    public static event Action? Changed;

    public static async Task WriteAsync(IEnumerable<CookieRecord> cookies)
    {
        Directory.CreateDirectory(AppSettings.DataDir);
        await File.WriteAllTextAsync(CookieFile, ToNetscape(cookies));
        Changed?.Invoke();
    }
}
