# Regenerates VidFlow.Core/Localization/Strings.resx (English, neutral) and Strings.zh.resx (Chinese)
# from Strings.tsv (columns: key, en, zh). Edit the TSV, then run:  pwsh tools/gen-strings.ps1
$ErrorActionPreference = 'Stop'
$dir = Join-Path $PSScriptRoot '..\VidFlow.Core\Localization'
$rows = Import-Csv (Join-Path $dir 'Strings.tsv') -Delimiter "`t" -Encoding UTF8

$dupes = $rows | Group-Object key | Where-Object Count -gt 1
if ($dupes) { throw "Duplicate keys: $($dupes.Name -join ', ')" }
$empty = $rows | Where-Object { -not $_.en -or -not $_.zh }
if ($empty) { throw "Missing translations: $($empty.key -join ', ')" }

function Write-Resx($path, $column) {
    $header = @'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen-strings.ps1 from Strings.tsv. Do not edit by hand. -->
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
'@
    $sb = [System.Text.StringBuilder]::new($header)
    foreach ($r in $rows | Sort-Object key) {
        $value = [System.Security.SecurityElement]::Escape($r.$column)
        [void]$sb.AppendLine("  <data name=""$($r.key)"" xml:space=""preserve""><value>$value</value></data>")
    }
    [void]$sb.AppendLine('</root>')
    [System.IO.File]::WriteAllText($path, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))
}

Write-Resx (Join-Path $dir 'Strings.resx') 'en'
Write-Resx (Join-Path $dir 'Strings.zh.resx') 'zh'
"Generated $($rows.Count) strings."
